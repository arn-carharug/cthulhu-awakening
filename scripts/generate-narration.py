"""Offline English narration. Requires the ignored Piper tools and system FFmpeg."""
import json
import shutil
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.tools/narration/python'))
import numpy as np
from piper import PiperVoice, SynthesisConfig
from piper.phonemize_espeak import ESPEAK_DATA_DIR

target = ROOT / 'assets/audio/narration'
source = target / 'source/en'
delivery = target / 'en'
source.mkdir(parents=True, exist_ok=True)
delivery.mkdir(parents=True, exist_ok=True)
model = ROOT / '.tools/narration/model'
voice = PiperVoice.load(model / 'en_US-libritts_r-medium.onnx')
# eSpeak's Windows C bridge requires an ASCII data path; the workspace contains ü.
phoneme_data = Path(tempfile.gettempdir()) / 'cthulhu-piper-1.3.0-espeak-ng-data'
shutil.copytree(ESPEAK_DATA_DIR, phoneme_data, dirs_exist_ok=True)
voice.espeak_data_dir = phoneme_data

def synthesize(text, path, speaker, length=1.4):
    np.random.seed(17)
    with wave.open(str(path), 'wb') as wav:
        voice.synthesize_wav(text, wav, syn_config=SynthesisConfig(speaker_id=speaker, length_scale=length, noise_scale=0.45, noise_w_scale=0.6))

def estimate_pitch(path):
    with wave.open(str(path)) as wav:
        rate = wav.getframerate()
        data = np.frombuffer(wav.readframes(wav.getnframes()), dtype=np.int16).astype(float)
    pitches = []
    for start in range(0, len(data)-2048, 1024):
        frame = data[start:start+2048]
        frame -= frame.mean()
        if np.sqrt(np.mean(frame**2)) < 700:
            continue
        correlation = np.correlate(frame, frame, mode='full')[2047:]
        first, last = int(rate/250), int(rate/65)
        lag = first + int(np.argmax(correlation[first:last]))
        if correlation[lag] > correlation[0] * 0.45:
            pitches.append(rate / lag)
    return float(np.median(pitches)) if pitches else 300

# Compare a few built-in narrator indices without copying any real person's voice.
samples = ROOT / '.tools/narration/auditions'
samples.mkdir(parents=True, exist_ok=True)
auditions = []
for speaker in range(6):
    path = samples / f'speaker-{speaker}.wav'
    synthesize('You are no longer alone. It sees you.', path, speaker)
    pitch = estimate_pitch(path)
    auditions.append({'speaker': speaker, 'estimatedPitchHz': round(pitch, 1)})
    print(auditions[-1], flush=True)
selected = min(auditions, key=lambda candidate: abs(candidate['estimatedPitchHz'] - 105))['speaker']
print(f'Selected built-in narrator {selected}', flush=True)
lines = json.loads((ROOT / 'scripts/narration-lines.json').read_text(encoding='utf-8'))
entries = {}
for line in lines:
    clean = source / f"{line['id']}.wav"
    output = delivery / f"{line['id']}.mp3"
    synthesize(line.get('spoken', line['text']), clean, selected)
    filters = 'silenceremove=start_periods=1:start_threshold=-48dB:start_silence=0.06,asetrate=19845,aresample=22050,atempo=0.98,highpass=f=85,lowpass=f=6200,aecho=0.8:0.65:125|240:0.12|0.06,loudnorm=I=-19:TP=-2:LRA=7,afade=t=in:d=0.025'
    subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(clean), '-af', filters, '-ar', '22050', '-ac', '1', '-b:a', '64k', str(output)], check=True)
    info = json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'json', str(output)]))
    duration = round(float(info['format']['duration']), 3)
    if duration > line.get('maxSeconds', 60):
        raise ValueError(f"{line['id']} exceeds its timeline slot: {duration}s")
    entries[line['id']] = {key: value for key, value in line.items() if key not in ['spoken', 'maxSeconds']}
    entries[line['id']].update({'file': f"assets/audio/narration/en/{output.name}", 'duration': duration, 'bytes': output.stat().st_size})
    print(f"{line['id']}: {duration}s", flush=True)

provenance = json.loads((model / 'provenance.json').read_text(encoding='utf-8'))
provenance.update({'engine': 'piper-tts 1.3.0', 'speakerIndex': selected, 'auditions': auditions, 'note': 'Pitch measurements are not a human listening assessment.'})
(target / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2) + '\n', encoding='utf-8')
shutil.copyfile(model / 'MODEL_CARD', target / 'MODEL_CARD.txt')
catalog = {'defaultLanguage': 'en', 'languages': {'en': entries}}
(target / 'manifest.json').write_text(json.dumps(catalog, indent=2) + '\n', encoding='utf-8')
(ROOT / 'js/narration-catalog.js').write_text('// Generated by scripts/generate-narration.py; edit scripts/narration-lines.json.\nwindow.NarrationCatalog = ' + json.dumps(catalog, indent=2) + ';\n', encoding='utf-8')
assert sum(entry['bytes'] for entry in entries.values()) <= 3 * 1024 * 1024
